"""
train_synth.py
==============
Train PhotozMLPVAE on **synthetic SEDs** generated by the Speculator/FSPS
surrogate, where the true SPS parameters are known.

Unlike train.py (which uses real LSST+Euclid photometry with unknown SPS
parameters), this script:

  1. Loads true 16-dim SPS parameters from sed_generation/data/sed_*.h5.
  2. Runs the frozen Speculator + FilterConv forward pass to get noiseless
     AB magnitudes in all 10 bands.
  3. Assigns synthetic photometric uncertainties (LSST DP1 + Euclid ERO depths).
     Magnitudes stay noiseless so the frozen decoder's reconstruction of the
     true SED falls exactly on the input photometry.
  4. Trains the MLPVAE with the same Phase-1 / Phase-2 schedule as train.py.
  5. At evaluation, passes the known true SPS parameters (theta_true, shape
     N_gal × 16) to plot_corner_posteriors so ALL 16 parameter truth values
     appear as gold lines on the corner plots.

Noise model
-----------
  For each band b with 5σ limiting magnitude m_5σ[b]:

      SNR_phot = 5 × 10^{−0.4 (m − m_5σ)}
      σ_m      = sqrt( (2.5 / (ln10 × SNR_phot))^2 + σ_cal^2 )

  A band is "detected" (mask = 1) when the noiseless mag satisfies
  0 < m < 35 and the computed σ_m is finite and positive — mirroring the
  criterion used by _raw_mags_errs_mask for real data.
  Approximate depths used (can be overridden via --m5sig):
      LSST u/g/r/i/z/y : 25.0 / 26.5 / 26.3 / 25.7 / 25.0 / 23.4
      Euclid VIS/Y/J/H : 25.5 / 24.0 / 24.0 / 24.0

Usage
-----
    conda run -n WL_ML_Challenge python photoz_mlpvae/scripts/train_synth.py
    conda run -n WL_ML_Challenge python photoz_mlpvae/scripts/train_synth.py \\
        --model-name mlpvae_synth_v1 --n-train 200000

Outputs  (photoz_mlpvae/trained/<MODEL_NAME>/)
---------------------------------------------
  best.pt
  config.yaml
  train.log
  train_curves.png
  test_scatter.png
  test_predictions.csv        z_true, z_pred, z_std, delta_z, + 16 theta cols
  test_metrics_paper_style.png
  test_pit.png
  corner_<label>.png          corner plots with ALL 16 true SPS params marked
"""

