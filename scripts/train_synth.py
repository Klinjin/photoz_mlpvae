def load_theta_hdf5(h5path, n_max, rng, start_row=0):
    """
    Load SPS parameters from an HDF5 file and (optionally) subsample.

    Parameters
    ----------
    h5path    : str
    n_max     : int or None  maximum number of rows to return
    rng       : np.random.Generator
    start_row : int          first row to consider (for val/test splitting)

    Returns
    -------
    theta : (N, 16) float32 array of physical SPS parameters
    """
    with h5py.File(h5path, "r") as f:
        n_total = f["parameters"].shape[0]
        available = n_total - start_row
        if n_max is None or n_max >= available:
            end_row = n_total
        else:
            end_row = start_row + n_max
        # Contiguous slice — far faster than fancy/random indexing on large HDF5 files.
        # Synthetic data is already randomly ordered so order-based selection is fine.
        theta = f["parameters"][start_row:end_row].astype(np.float32)
    return theta


def generate_photometry_gpu(theta, model_dec, device, batch_size=1024):
    """
    Run true SPS parameters through the frozen Speculator + FilterConv to
    obtain noiseless AB magnitudes.

    Parameters
    ----------
    theta     : (N, 16) float32 numpy array – physical SPS parameters
                  [zred, logmass, logzsol, dust2, dust1_fraction, dust_index,
                   gas_logz, fagn, agn_tau, igm_scale, logsfr_ratios_0..5]
    model_dec : PhotozMLPVAE instance (only decoder is used; must be on device)
    device    : str

    Returns
    -------
    mags_noiseless : (N, 10) float32 – noiseless AB magnitudes
    """
    model_dec.eval()
    mags_list = []
    n = theta.shape[0]
    for i in range(0, n, batch_size):
        theta_b = torch.from_numpy(theta[i:i + batch_size]).to(device)
        with torch.no_grad():
            log_spec, _ = model_dec.speculator(theta_b)
            m_ab = model_dec.filter_conv(
                log_spec, theta_b[:, 0], theta_b[:, 1]
            )   # (batch, 10)
        mags_list.append(m_ab.cpu().numpy())
    return np.concatenate(mags_list, axis=0).astype(np.float32)   # (N, 10)


def add_photometric_errors(mags_noiseless,
                           m5sig=None, calib_floor=CALIB_FLOOR,
                           i_band_snr_min=I_BAND_SNR_MIN):
    """
    Assign synthetic photometric uncertainties WITHOUT adding Gaussian noise.

    Because the decoder is the same Speculator used to generate the data, the
    noiseless magnitudes are kept as 'observed' photometry so that the
    reconstruction of the true SED at z_true falls exactly on the input
    photometry.  Only the uncertainty (σ_m) is computed from the noise model:

        SNR_phot = 5 × 10^{−0.4 (m − m_5σ)}   (per-band)
        σ_m      = sqrt( (2.5 / (ln10 × SNR_phot))^2 + calib_floor^2 )

    Detection criterion mirrors _raw_mags_errs_mask for real data:
        m_ok = 0 < m < 35 and finite
        e_ok = σ_m > 0 and finite
        detected = m_ok & e_ok

    Parameters
    ----------
    mags_noiseless : (N, B) float32
    m5sig          : (B,) float32 – 5σ limiting magnitudes; defaults to M_5SIG
    calib_floor    : float – calibration noise floor in magnitudes
    i_band_snr_min : float or None – minimum i-band (index 3) SNR for a galaxy
                     to be included; None or 0 disables the cut

    Returns
    -------
    mags_out : (N, B) float32  NaN where undetected (noiseless otherwise)
    errs     : (N, B) float32  NaN where undetected
    mask     : (N, B) float32  1 = detected, 0 = undetected
    gal_keep : (N,)   bool     True for galaxies passing the i-band SNR cut
    """
    if m5sig is None:
        m5sig = M_5SIG
    m5sig = np.asarray(m5sig, dtype=np.float32)[None, :]   # (1, B)

    snr_phot = 5.0 * np.power(10.0, -0.4 * (mags_noiseless - m5sig))

    # Galaxy-level i-band SNR cut (use raw SNR before clipping)
    if i_band_snr_min:
        gal_keep = snr_phot[:, 3] >= i_band_snr_min
    else:
        gal_keep = np.ones(len(mags_noiseless), dtype=bool)

    snr_phot = np.clip(snr_phot, 1e-3, None)                # avoid /0

    sig_phot = (2.5 / np.log(10.0)) / snr_phot
    errs     = np.sqrt(sig_phot ** 2 + calib_floor ** 2).astype(np.float32)

    # Mirror the real-data detection criterion in _raw_mags_errs_mask
    m_ok     = np.isfinite(mags_noiseless) & (mags_noiseless > 0) & (mags_noiseless < 35)
    e_ok     = np.isfinite(errs) & (errs > 0)
    detected = m_ok & e_ok
    mask     = detected.astype(np.float32)

    mags_out = mags_noiseless.copy()
    mags_out[~detected] = np.nan
    errs[~detected]     = np.nan

    return mags_out, errs, mask, gal_keep


def mags_to_dataframe(mags, errs, z_spec, mag_cols=MAG_COLS, err_cols=ERR_COLS):
    """
    Build a pandas DataFrame with the column names expected by build_features.

    Parameters
    ----------
    mags     : (N, B) float32  noisy AB mags  (NaN = undetected)
    errs     : (N, B) float32  mag errors     (NaN = undetected)
    z_spec   : (N,)   float32  true redshifts
    mag_cols : list of B magnitude column names  (default: all 10 bands)
    err_cols : list of B error column names      (default: all 10 bands)

    Returns
    -------
    df : pd.DataFrame  with columns mag_cols + err_cols + [TARGET_COL]
    """
    data = {}
    for j, (mc, ec) in enumerate(zip(mag_cols, err_cols)):
        data[mc] = mags[:, j]
        data[ec] = errs[:, j]
    data[TARGET_COL] = z_spec
    return pd.DataFrame(data)


