def append_detection_features(X: np.ndarray, mask: np.ndarray) -> np.ndarray:
    """
    Append 2 detection-rate features to the 40-dim encoder input.

    The trunk collapses high-z galaxies to a single representation because
    their Lyman-break band-dropouts produce near-identical 40-dim feature
    vectors: detected bands have similar colours, non-detected bands carry
    only the sentinel/flag pattern.  Providing the *count* of detected bands
    explicitly breaks this degeneracy without requiring the ResBlock to
    reverse-engineer it from 20 missingness flags.

    Columns appended (both in [0, 1], no additional scaling needed):
      D+0: frac_detected      = n_bands_detected / B  (B = total bands in mask)
           Overall photometry coverage; discriminates sparse from rich SEDs.
      D+1: frac_blue_detected = (u + g + r detected) / 3
           Lyman-break proxy: 0 → all three blue LSST bands missing (z > ~4.5);
           0.33 → only u missing (z > ~2); 1 → fully blue-detected (z < ~2).

    Parameters
    ----------
    X    : (N, D)   float32  encoder features from build_features
    mask : (N, 10)  float32  band-presence mask (1=detected) from build_features

    Returns
    -------
    X_out : (N, D+2) float32
    """
    frac_det  = mask.mean(axis=1, keepdims=True)        # (N, 1)  all 10 bands
    frac_blue = mask[:, :3].mean(axis=1, keepdims=True) # (N, 1)  u, g, r only
    return np.concatenate([X, frac_det, frac_blue], axis=1).astype(np.float32)


