class _Tee:
    def __init__(self, stream, fpath):
        self._stream = stream
        self._file   = open(fpath, "a", buffering=1)

    def write(self, data):
        self._stream.write(data)
        self._file.write(data)

    def flush(self):
        self._stream.flush()
        self._file.flush()

    def close(self):
        self._file.close()

    def __getattr__(self, attr):
        return getattr(self._stream, attr)


